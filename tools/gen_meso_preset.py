"""Write the Meso Keymap preset ``src/meso/presets/keyconfig/Meso.py`` from the binding table.

    python3 tools/gen_meso_preset.py           # (re)write the preset
    python3 tools/gen_meso_preset.py --check   # exit 1 when the preset is out of date

The preset is self-contained: Blender runs it (its keymap import, then every start-up) like its
own ``Industry_Compatible.py``, which it mirrors: it reads Blender's Industry Compatible keymap
data the same way that preset does, puts the Meso tier's items (``core.meso_bindings
.merge_keyconfig_data``'s rule, written out here as plain data) first in their keymaps and
switches off the Industry Compatible items the table says (``Displaced.off``). It loads no
module of Meso Mode. A unit test runs ``--check``. Standard library only (this tool imports
the pure ``core`` package directly).
"""

from __future__ import annotations

import argparse
import importlib
import importlib.util
import pathlib
import pprint
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
CORE = ROOT / "src" / "meso" / "core"
PRESET = ROOT / "src" / "meso" / "presets" / "keyconfig" / "Meso.py"


def _core():
    name = "_meso_core_gen"
    if name not in sys.modules:
        spec = importlib.util.spec_from_file_location(
            name, CORE / "__init__.py", submodule_search_locations=[str(CORE)])
        module = importlib.util.module_from_spec(spec)
        sys.modules[name] = module
        spec.loader.exec_module(module)
    return importlib.import_module(name + ".meso_bindings")


def _key_args(key) -> dict:
    args = {"type": key.type, "value": key.value}
    for name in ('ctrl', 'shift', 'alt', 'oskey'):
        if getattr(key, name):
            args[name] = True
    return args


def _without_props(entry):
    idname, args, data = entry
    data = {k: v for k, v in (data or {}).items() if k != "properties"}
    return (idname, args, data or None)


def render() -> str:
    """The preset's source text for the current table."""
    mb = _core()
    bindings = mb.keyconfig_bindings()
    active = {b.id: b.default_on for b in bindings}
    by_keymap = mb.items_by_keymap(bindings)
    items = [(name, [_without_props(mb.item_data(item, active[bid])) for bid, item in pairs])
             for name, pairs in by_keymap.items()]
    props = [(name, [mb.raw_props(item) for _bid, item in pairs])
             for name, pairs in by_keymap.items()
             if any(item.props for _bid, item in pairs)]
    off = [(d.keymap, d.native, _key_args(d.key)) for b in bindings for d in b.displaces if d.off]
    body = pprint.pformat(items, width=96, sort_dicts=False)
    props_body = pprint.pformat(props, width=96, sort_dicts=False)
    off_body = pprint.pformat(off, width=96, sort_dicts=False)
    return f'''# SPDX-License-Identifier: GPL-3.0-or-later
# Generated by tools/gen_meso_preset.py from the Meso key table: do not edit by hand.
"""The Meso Keymap: Blender's Industry Compatible keymap with the Meso keys first.

"Use the Meso Keymap" in Meso Mode runs Blender's own keymap import on this file: Blender copies
it into the user's keymap presets and selects it, and runs it at every start-up, exactly as it
runs its own ``Industry_Compatible.py``, which this mirrors. The Meso Mode keys that are free in
every keymap are add-on keys and are not repeated here. Edit, switch off or restore any item in
Blender's keymap editor; remove the keymap with the "-" next to Preferences > Keymap's menu.
"""

import os

import bpy

DIRNAME, FILENAME = os.path.split(__file__)
IDNAME = os.path.splitext(FILENAME)[0]

# (keymap name, items) put first in their keymap, in ``keyconfig_init_from_data`` format, without
# their properties: ``load()`` sets those (MESO_PROPS).
MESO_ITEMS = {body}

# (keymap name, [[(property, value, raw value)] per item of its MESO_ITEMS entry]). At start-up
# Blender loads the selected keymap before it registers the extensions, so Meso Mode's operators
# do not exist yet: their properties are stored raw (an enum by its index), as ID properties,
# and Blender types them when the operator registers.
MESO_PROPS = {props_body}

# (keymap name, native call, key) of the Industry Compatible items switched off here: Meso's own
# item on that key passes it on where the native one would stop it.
SWITCHED_OFF = {off_body}

industry_compatible = bpy.utils.execfile(os.path.join(
    bpy.utils.system_resource('SCRIPTS'), "presets", "keyconfig", "keymap_data",
    "industry_compatible_data.py"))


def _native_call(idname, data):
    props = (data or {{}}).get("properties") or ()
    args = ", ".join("{{}}={{!r}}".format(name, value) for name, value in sorted(props))
    return "{{}}({{}})".format(idname, args)


def _same_key(args, key):
    if not isinstance(args, dict) or args.get("any") or args.get("key_modifier"):
        return False
    return all(args.get(name, False) == key.get(name, False)
               for name in ("type", "value", "ctrl", "shift", "alt", "oskey"))


def keyconfig_data(params):
    """Industry Compatible's keyconfig data with the Meso items."""
    data = industry_compatible.generate_keymaps(params)
    by_name = {{}}
    for name, _args, content in data:
        by_name.setdefault(name, content)
    for name, native, key in SWITCHED_OFF:
        items = by_name[name]["items"]
        for i, (idname, args, extra) in enumerate(items):
            if _same_key(args, key) and _native_call(idname, extra) == native:
                items[i] = (idname, args, dict(extra or {{}}, active=False))
    for name, entries in MESO_ITEMS:
        by_name[name]["items"][0:0] = list(entries)
    return data


def load():
    from sys import platform
    from bl_keymap_utils.io import keyconfig_init_from_data

    prefs = bpy.context.preferences

    kc = bpy.context.window_manager.keyconfigs.new(IDNAME)
    params = industry_compatible.Params(use_mouse_emulate_3_button=prefs.inputs.use_mouse_emulate_3_button)
    keyconfig_data_ = keyconfig_data(params)

    if platform == "darwin":
        from bl_keymap_utils.platform_helpers import keyconfig_data_oskey_from_ctrl_for_macos
        keyconfig_data_ = keyconfig_data_oskey_from_ctrl_for_macos(keyconfig_data_)

    keyconfig_init_from_data(kc, keyconfig_data_)
    _set_meso_props(kc)


def _set_meso_props(kc):
    """The MESO_PROPS of the Meso items (the first items of their keymaps)."""
    for name, per_item in MESO_PROPS:
        km = kc.keymaps.get(name)
        if km is None:
            continue
        for kmi, props in zip(km.keymap_items, per_item):
            known = kmi.properties.bl_rna.properties
            for prop, value, raw in props:
                if prop in known:
                    setattr(kmi.properties, prop, value)
                else:
                    kmi.properties[prop] = raw


if __name__ == "__main__":
    load()
'''


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true", help="exit 1 when the preset is stale")
    args = ap.parse_args(argv)
    text = render()
    current = PRESET.read_text(encoding="utf-8") if PRESET.is_file() else None
    if args.check:
        if current != text:
            print(f"{PRESET.relative_to(ROOT)} is out of date: run tools/gen_meso_preset.py",
                  file=sys.stderr)
            return 1
        return 0
    if current != text:
        PRESET.parent.mkdir(parents=True, exist_ok=True)
        PRESET.write_text(text, encoding="utf-8")
        print(f"wrote {PRESET.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
