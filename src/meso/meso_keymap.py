"""Meso keys: the base add-on keys, the Meso Keymap's state and the first-enable note.

Contract: local/docs/meso-keymap-interfaces.md ("Delivery model", "Lifecycle").

- **Base keys** (``core.meso_bindings.base_bindings``: free in Blender's default keymap and in
  Industry Compatible): items of ``wm.keyconfigs.addon``, registered here and removed on
  unregister, nothing else. They work with every keymap.
- **The Meso Keymap** (optional, recommended): a keyconfig named "Meso". ``keymap/Meso.py``
  (generated by ``tools/gen_meso_preset.py``: self-contained, it loads no Meso module) is
  imported with Blender's keymap import: by the user (it is also a separate file of each GitHub
  release), or, in the full (GitHub) build only, by ``meso.keymap_install`` on the user's click
  (``ops/keymap_install.py``, which hands its button and hint over with ``set_installer``; the
  extensions-platform build has neither it nor ``keymap/``).
  Blender copies it into the user's keymap presets, selects it and selects it again at every
  start-up (before the extensions register: the preset sets Meso's operator properties raw
  then, see ``core.meso_bindings.ENUM_PROPS``). This module only READS which keymap is active
  and the version line of the user's copy (missing, current or out of date,
  ``core.meso_keymap_version``); it never imports, selects, restores, resets or edits a
  keyconfig or a keymap item.
- ``register()`` shows a note (a dialog, never under ``-b``) once after the first enable: the
  extensions-platform build's is informational only (the optional keymap and its instructions
  are on GitHub); the full build's offers its one-click install, and comes back once per keymap
  version while the active Meso keymap's copy is out of date. The note changes nothing itself.

The Plaza's own Space items live in ``keymaps.py``. This module is LAST in
``__init__._modules``: the items need the operator classes, and they go first on unregister.
"""

from __future__ import annotations

import os
import re

import bpy

from . import prefs
from .core import meso_bindings as mb
from .core.meso_keymap_version import MESO_KEYMAP_VERSION

LOG_PREFIX = "Meso Mode:"
PROMPT_DELAY = 0.5
REPO_URL = "https://github.com/anoxdetox/meso"   # the keymap file and its install instructions
PRESET_NONE, PRESET_CURRENT, PRESET_OUTDATED = 'NONE', 'CURRENT', 'OUTDATED'
_VERSION_LINE = re.compile(r"^# Meso keymap version: ([0-9a-f]+)\s*$", re.MULTILINE)

# (binding id, KeyMap, KeyMapItem, table Item) of every registered base add-on item.
_items: list[tuple[str, bpy.types.KeyMap, bpy.types.KeyMapItem, mb.Item]] = []


# ------------------------------------------------------------------------------ reading state


def _prefs(context=None):
    try:
        return prefs.get_prefs(context or bpy.context)
    except Exception:
        return None


def _keyconfigs(context=None):
    wm = getattr(context or bpy.context, 'window_manager', None)
    return getattr(wm, 'keyconfigs', None)


def active_keyconfig_name(context=None) -> str | None:
    active = getattr(_keyconfigs(context), 'active', None)
    return getattr(active, 'name', None)


def is_meso_active(context=None) -> bool:
    return active_keyconfig_name(context) == mb.MESO_NAME


def operator_exists(idname: str) -> bool:
    module, _dot, name = idname.partition('.')
    try:
        getattr(getattr(bpy.ops, module), name).get_rna_type()
    except (AttributeError, KeyError):
        return False
    return True


def meso_keyconfig(context=None):
    """The loaded "Meso" keyconfig (active or not), or None."""
    keyconfigs = _keyconfigs(context)
    return keyconfigs.get(mb.MESO_NAME) if keyconfigs is not None else None


def _find(kc, name):
    space, region = mb.KEYMAP_SPACES[name]
    return kc.keymaps.find(name, space_type=space, region_type=region)


# id(table Item) -> (table index, binding id); the table is immutable.
_TABLE = {id(item): (n, bid) for n, (bid, item) in enumerate(mb.table_items())}


def binding_of(item: mb.Item) -> str:
    """The binding id of a table item."""
    return _TABLE[id(item)][1]


def registered() -> list[tuple[str, bpy.types.KeyMap, bpy.types.KeyMapItem, mb.Item]]:
    """A copy of the registered base add-on items ``(binding id, km, kmi, Item)``."""
    return list(_items)


def meso_items(context=None) -> list:
    """``[(km, kmi, Item)]`` of the Meso tier's items in the loaded Meso keyconfig, in table
    order. The preset put each keymap's items first, in table order, so the n-th item of a
    keymap's block is its n-th table item (checked by idname and key type)."""
    kc = meso_keyconfig(context)
    if kc is None:
        return []
    out = []
    for name, pairs in mb.items_by_keymap(mb.keyconfig_bindings()).items():
        km = _find(kc, name)
        if km is None:
            continue
        kmis = km.keymap_items
        for i, (_bid, item) in enumerate(pairs):
            if i < len(kmis) and kmis[i].idname == item.idname and kmis[i].type == item.key.type:
                out.append((_TABLE[id(item)][0], km, kmis[i], item))
    out.sort(key=lambda t: t[0])
    return [t[1:] for t in out]


def user_items(binding_id: str | None = None, context=None) -> list:
    """``[(user km, user kmi, Item)]``: the user-keyconfig copies (what the keymap editor
    edits) of the base add-on items, and of the Meso Keymap's items while it is the active
    keymap, in table order; found with ``find_match`` (it follows the item id, also after a
    rebind). Read only."""
    keyconfigs = _keyconfigs(context)
    user = getattr(keyconfigs, 'user', None)
    if user is None:
        return []
    sources = [(km, kmi, item) for _bid, km, kmi, item in _items]
    if is_meso_active(context):
        sources += meso_items(context)
    out = []
    for km, kmi, item in sources:
        if binding_id is not None and binding_of(item) != binding_id:
            continue
        try:
            ukm = user.keymaps.find(km.name, space_type=km.space_type,
                                    region_type=km.region_type)
            found = ukm.keymap_items.find_match(km, kmi) if ukm is not None else None
        except ReferenceError:
            continue
        if found is not None:
            out.append((ukm, found, item))
    out.sort(key=lambda t: _TABLE[id(t[2])][0])
    return out


def live_ids(context=None) -> tuple[str, ...]:
    """The bindings with at least one item switched on in the user keymap, in table order."""
    on = {binding_of(item) for _km, kmi, item in user_items(context=context) if kmi.active}
    return tuple(b.id for b in mb.BINDINGS if b.id in on)


def live_bindings(context=None) -> tuple[mb.Binding, ...]:
    ids = set(live_ids(context))
    return tuple(b for b in mb.BINDINGS if b.id in ids)


def off_bindings(context=None) -> tuple[mb.Binding, ...]:
    """The bindings whose items are all switched off (or deleted) in the user keymap while
    the Meso Keymap is active, in table order (empty otherwise); ``mb.warnings(..., inactive=)``."""
    if not is_meso_active(context):
        return ()
    ids = set(live_ids(context))
    return tuple(b for b in mb.BINDINGS if b.id not in ids)


# ------------------------------------------------------------------------------ the user's copy


def copy_version(path) -> str | None:
    """The version line of a Meso keymap file (its first lines), or None."""
    try:
        with open(path, 'r', encoding='utf-8') as f:
            head = f.read(1024)
    except (OSError, UnicodeDecodeError):
        return None
    m = _VERSION_LINE.search(head)
    return m.group(1) if m else None


_hooks = {'installer': None}


def set_installer(installer) -> None:
    """Set by the full build's ``ops/keymap_install.py`` on register (None on unregister): an
    object with ``hint`` (text) and ``button(layout, outdated)``."""
    _hooks['installer'] = installer


def installer():
    """The full build's one-click install hooks, or None (the extensions-platform build)."""
    return _hooks['installer']


def install_available() -> bool:
    return installer() is not None


def note_pending(context=None) -> bool:
    """The note is due: never shown (and the Meso keymap not active), or, with the full build's
    installer, the active Meso keymap's copy is out of date and the note was not shown for this
    version yet. The extensions-platform build's note is shown once, ever."""
    p = _prefs(context)
    if p is None:
        return False
    if is_meso_active(context):
        if not install_available():
            return False
        return (preset_state() == PRESET_OUTDATED
                and getattr(p, 'keymap_noted_version', '') != MESO_KEYMAP_VERSION)
    return not p.keymap_prompted


def installed_preset_path() -> str | None:
    """The user's copy of the Meso keymap in Blender's user keymap presets (where Blender's
    keymap import put it), or None. Read only: nothing is created."""
    try:
        folder = bpy.utils.user_resource('SCRIPTS', path=os.path.join("presets", "keyconfig"))
    except Exception:
        return None
    path = os.path.join(folder, mb.MESO_NAME + ".py") if folder else ""
    return path if path and os.path.isfile(path) else None


_state_cache: dict[tuple, str] = {}


def preset_state() -> str:
    """``PRESET_NONE`` (no copy), ``PRESET_CURRENT`` (the version this Meso Mode matches) or
    ``PRESET_OUTDATED`` (another one: import the release's file again). Cached by the copy's
    path, mtime and size (the preferences draw it)."""
    path = installed_preset_path()
    if path is None:
        return PRESET_NONE
    try:
        st = os.stat(path)
    except OSError:
        return PRESET_NONE
    key = (path, st.st_mtime_ns, st.st_size)
    if key not in _state_cache:
        _state_cache.clear()
        _state_cache[key] = (PRESET_CURRENT if copy_version(path) == MESO_KEYMAP_VERSION
                             else PRESET_OUTDATED)
    return _state_cache[key]


# ------------------------------------------------------------------------------ base add-on items


def _add(kc, bid: str, b_on: bool, item: mb.Item) -> None:
    space, region = mb.KEYMAP_SPACES[item.keymap]
    km = kc.keymaps.new(item.keymap, space_type=space, region_type=region)
    k = item.key
    kmi = km.keymap_items.new(item.idname, k.type, k.value, ctrl=k.ctrl, shift=k.shift,
                              alt=k.alt, oskey=k.oskey, repeat=False)
    for name, value in item.props:
        setattr(kmi.properties, name, value)
    kmi.active = b_on
    _items.append((bid, km, kmi, item))


def remove_base_items() -> None:
    """Remove every registered base item, newest first. Never raises."""
    for _bid, km, kmi, _item in reversed(_items):
        try:
            km.keymap_items.remove(kmi)
        except (ReferenceError, RuntimeError):
            pass
    _items.clear()


def register_base_items(context=None) -> int:
    """Register the base tier as add-on items (replacing any); returns the number of items.
    A failure is logged and leaves nothing half registered."""
    remove_base_items()
    kc = getattr(_keyconfigs(context), 'addon', None)
    if kc is None:
        return 0
    try:
        for b in mb.base_bindings():
            for item in b.items:
                if operator_exists(item.idname):
                    _add(kc, b.id, b.default_on, item)
    except Exception as ex:
        print(LOG_PREFIX, f"registering the Meso keys failed: {ex!r}")
        remove_base_items()
    return len(_items)


# ------------------------------------------------------------------------------ the question


def _mark_dirty(context=None):
    try:
        (context or bpy.context).preferences.is_dirty = True
    except (AttributeError, TypeError):
        pass


def _prompt_tick():
    """One-shot timer: open the first-enable note (never in background mode)."""
    try:
        if bpy.app.background:
            return None
        context = bpy.context
        wm = context.window_manager
        p = _prefs(context)
        if p is None or not wm.windows or not note_pending(context):
            return None
        p.keymap_prompted = True
        if is_meso_active(context):
            p.keymap_noted_version = MESO_KEYMAP_VERSION
        _mark_dirty(context)
        with context.temp_override(window=wm.windows[0]):
            bpy.ops.meso.keymap_choice_dialog('INVOKE_DEFAULT')
    except Exception as ex:
        print(LOG_PREFIX, f"could not open the Meso Keymap note: {ex!r}")
    return None


def _cancel_prompt():
    if bpy.app.timers.is_registered(_prompt_tick):
        try:
            bpy.app.timers.unregister(_prompt_tick)
        except ValueError:
            pass


def prompt_pending() -> bool:
    return bpy.app.timers.is_registered(_prompt_tick)


# ------------------------------------------------------------------------------ register


def register() -> None:
    """RestrictBlend-safe: only ``window_manager`` and ``preferences`` are used."""
    context = bpy.context
    register_base_items(context)
    p = _prefs(context)
    if p is not None and not bpy.app.background:
        _cancel_prompt()
        bpy.app.timers.register(_prompt_tick, first_interval=PROMPT_DELAY)


def unregister() -> None:
    """Stop the prompt, remove the base items. Never touches a keyconfig or the user's copy
    of the preset. Never raises."""
    _cancel_prompt()
    remove_base_items()


def keep_user_edits() -> None:
    """End of the package's ``unregister()`` (the operators are gone): a keyconfig update that
    keeps the operator properties of the user's own edits of Meso keys, so they apply again on
    the next enable (Blender's script reload does the same). Edits nothing. Never raises."""
    try:
        bpy.context.window_manager.keyconfigs.update(keep_properties=True)
    except Exception as ex:
        print(LOG_PREFIX, f"keeping the keymap edits failed: {ex!r}")
